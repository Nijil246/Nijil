import {db} from "hatchable";
export const access="user";
export const methods=["GET","POST"];
export default async function(req,res){
  if(req.method==="GET"){
    const {rows}=await db.query("SELECT id,provider,status,card_brand,last4,currency,created_at FROM virtual_cards WHERE user_id=$1 ORDER BY created_at DESC LIMIT 1",[req.user.id]);
    return res.json({card:rows[0]||null,issuance_live:false,message:"A real Visa/Mastercard card requires an approved card issuer/program manager and KYC. No card number or CVV is generated by NEXGPAY."});
  }
  const {rows}=await db.query("SELECT id FROM virtual_cards WHERE user_id=$1 AND status IN ('PENDING_KYC','ISSUER_REQUIRED','ACTIVE') LIMIT 1",[req.user.id]);
  if(rows[0]) return res.json({card_id:rows[0].id,status:"ISSUER_REQUIRED",message:"Your virtual-card request is already registered."});
  const r=await db.query("INSERT INTO virtual_cards(user_id) VALUES($1) RETURNING id,status,currency,created_at",[req.user.id]);
  res.status(202).json({card:r.rows[0],message:"Virtual-card request registered. Connect an approved card issuer/program before activating spending."});
}